-- EchoNet: tabelas do servidor Express (não use a Data API diretamente no navegador).
-- Execute apenas em um projeto Supabase dedicado e vazio durante a migração.
-- Reexecutar esta estrutura não apaga dados existentes.
CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  ultimo_ativo TIMESTAMPTZ,
  bio TEXT DEFAULT '',
  display_name TEXT DEFAULT '',
  avatar TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_echonet_users_username_lower ON public.users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS idx_echonet_users_email_lower ON public.users (lower(email));

CREATE TABLE IF NOT EXISTS public.posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imagem TEXT NOT NULL,
  legenda TEXT NOT NULL,
  usuario TEXT NOT NULL,
  criado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  archived INTEGER NOT NULL DEFAULT 0 CHECK (archived IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_posts_author ON public.posts (usuario, criado_em DESC);

CREATE TABLE IF NOT EXISTS public.messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remetente TEXT NOT NULL,
  destinatario TEXT NOT NULL,
  conteudo TEXT NOT NULL,
  enviado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_pair ON public.messages (remetente, destinatario, id);

CREATE TABLE IF NOT EXISTS public.password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  token TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_password_resets_token ON public.password_resets (token);

CREATE TABLE IF NOT EXISTS public.post_likes (
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  post_id INTEGER NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, post_id)
);
CREATE TABLE IF NOT EXISTS public.saved_posts (
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  post_id INTEGER NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, post_id)
);
CREATE TABLE IF NOT EXISTS public.comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  post_id INTEGER NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  conteudo TEXT NOT NULL,
  criado_em TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_comments_post ON public.comments (post_id,id);
CREATE TABLE IF NOT EXISTS public.follows (
  follower_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  following_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  PRIMARY KEY (follower_id, following_id),
  CHECK (follower_id <> following_id)
);
CREATE INDEX IF NOT EXISTS idx_follows_following ON public.follows (following_id);

CREATE TABLE IF NOT EXISTS public.stories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  image_path TEXT NOT NULL,
  caption TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_stories_active ON public.stories (expires_at,id);
CREATE TABLE IF NOT EXISTS public.story_views (
  story_id INTEGER NOT NULL REFERENCES public.stories(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (story_id,user_id)
);
CREATE TABLE IF NOT EXISTS public.notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  actor_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  message TEXT NOT NULL,
  target_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_notifications_inbox ON public.notifications (recipient_id, id DESC);

-- O EchoNet autentica usuários no Express e conecta como backend.
-- A API REST/GraphQL pública do Supabase não pode ler esses registros.
